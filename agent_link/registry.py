"""User-level binding registry used for session-id discovery.

``bind`` (CLI) and the host service keep one JSON entry per binding in a
user-level directory (default ``~/.agent-link/registry/``, overridable with
the ``AGENT_LINK_REGISTRY`` environment variable).  Parent and child
framework adapters scan it to find the bindings that name their own session
id, so a session does not need per-binding environment variables to discover
what it is bound to.

The registry is a discovery pointer, not the source of truth: the SQLite
database under each runtime root stays authoritative.  A missing or stale
entry is regenerated by re-running ``bind`` (a replay is idempotent) or by
starting the host service for that binding.  Entries are never deleted
automatically.  The directory is 0700 and each entry 0600.
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path

from .storage import utc_now_iso, validate_identifier

REGISTRY_VERSION = 1
REGISTRY_ENV = "AGENT_LINK_REGISTRY"


def registry_dir() -> Path:
    """Directory holding the user-level binding registry."""
    override = os.environ.get(REGISTRY_ENV)
    if override:
        return Path(override).expanduser()
    return Path.home() / ".agent-link" / "registry"


def entry_from_row(root, row: dict) -> dict:
    """Build a registry entry from a ``bindings`` table row."""
    now = utc_now_iso()
    return {
        "version": REGISTRY_VERSION,
        "binding_id": row["binding_id"],
        "run_id": row["run_id"],
        "native_task_id": row["native_task_id"],
        "root": str(Path(root).resolve()),
        "parent": {"framework": row["parent_framework"], "session_id": row["parent_session_id"]},
        "child": {"framework": row["child_framework"], "session_id": row["child_session_id"]},
        "config_digest": row["config_digest"],
        "created_at": now,
        "updated_at": now,
    }


def write_entry(entry: dict, *, directory: Path | None = None) -> Path:
    """Write one registry entry atomically (0600 file, 0700 dir).

    ``created_at`` is preserved across rewrites of the same binding.  The file
    name is the validated binding_id, so no path traversal is possible.
    """
    binding_id = validate_identifier(entry.get("binding_id"), "binding_id")
    directory = Path(directory) if directory is not None else registry_dir()
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(directory, 0o700)
    target = directory / f"{binding_id}.json"
    try:
        existing = json.loads(target.read_text("utf-8"))
    except (OSError, json.JSONDecodeError):
        existing = None
    if isinstance(existing, dict) and existing.get("binding_id") == binding_id:
        created_at = existing.get("created_at")
        if isinstance(created_at, str) and created_at:
            entry["created_at"] = created_at
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".tmp-", suffix=".json")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(entry, stream, ensure_ascii=False, sort_keys=True)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(tmp, target)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return target


def _matches(entry: dict, filters: dict) -> bool:
    for (side, key), wanted in filters.items():
        if wanted is None:
            continue
        side_value = entry.get(side)
        if not isinstance(side_value, dict) or side_value.get(key) != wanted:
            return False
    return True


def list_bindings(
    *,
    directory: Path | None = None,
    parent_session_id: str | None = None,
    child_session_id: str | None = None,
    parent_framework: str | None = None,
    child_framework: str | None = None,
) -> list[dict]:
    """List registry entries matching the given filters, created_at ascending.

    A missing directory is an empty registry (normal before the first bind);
    an unreadable directory raises so the caller cannot mistake it for empty.
    Malformed entries are skipped.
    """
    directory = Path(directory) if directory is not None else registry_dir()
    if not directory.exists():
        return []
    if not directory.is_dir():
        raise OSError(f"registry path is not a directory: {directory}")
    filters = {
        ("parent", "session_id"): parent_session_id,
        ("child", "session_id"): child_session_id,
        ("parent", "framework"): parent_framework,
        ("child", "framework"): child_framework,
    }
    entries = []
    for path in sorted(directory.glob("*.json")):
        try:
            entry = json.loads(path.read_text("utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(entry, dict):
            continue
        if entry.get("version") != REGISTRY_VERSION:
            continue
        binding_id = entry.get("binding_id")
        if not isinstance(binding_id, str) or not binding_id:
            continue
        if not _matches(entry, filters):
            continue
        entries.append(entry)
    entries.sort(key=lambda entry: (str(entry.get("created_at") or ""), str(entry.get("binding_id") or "")))
    return entries
